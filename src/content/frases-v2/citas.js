// **Hay dos lotes y solo uno es elegible.** Las del lote C2 siguen en
// `pendiente_revision`: el texto se cotejó contra una edición concreta, pero
// falta la firma editorial y la jurídica, y el selector no las ve (solo elige
// `aprobada`). Las 464 del lote C3 están `aprobada`s, con las dos firmas del
// 14 de octubre de 2026.
//
// **El lote C3 abrió el criterio en dos puntos** (decisiones editoriales del
// 13 y 14 oct 2026, resumidas en `docs/frases-v2-fuentes.md`, «Criterio»):
//
//   · Además del dominio público, se admiten licencias abiertas de uso
//     comercial. La Biblia en Español Sencillo es CC BY 4.0 y **exige
//     atribución**: por eso su `atribucion` nombra a AudioBiblia.org / Irma
//     Flores y la licencia, y la app la pinta tal cual debajo de la frase y en
//     las fuentes de Tu perfil. Quitarla de la cadena rompe la licencia.
//   · Muchas citas son «Traducción editorial para Strivo» desde un texto de
//     dominio público. Su atribución lo dice, para no presentar como de otra
//     edición una traducción que es nuestra.
//
// El expediente de cada una —edición, ubicación, estado de derechos, qué se
// verificó, quién y cuándo, y qué falta— vive fuera del bundle, en
// `docs/frases-v2-fuentes.md`, bajo su `fuenteClave`. `scripts/validar-frases.js`
// falla si una cita no tiene expediente, y si una aprobada no tiene las dos
// firmas.
//
// **El texto es el de la edición, carácter por carácter**, con su ortografía:
// la Reina-Valera 1909 escribe «á» como preposición y Gracián «vezes». No se
// moderniza sin decidirlo antes en el expediente: una cita retocada deja de
// ser una cita. Las comillas no van aquí; las pone el componente.
//
// Para aprobar una cita: completar su expediente con las dos firmas, cambiar
// aquí su `estado` a `aprobada` y correr `node scripts/validar-frases.js`.

