/** Días que el repertorio actual aguanta sin repetir una frase (RN-HOY-02). */
export function diasSinRepetir(frases = FRASES) {
  return frases.length
}

/** Días transcurridos desde el 1 de enero de 1970, a partir de 'YYYY-MM-DD'. */
function diasDesdeEpoca(dateKey) {
  const [year, month, day] = String(dateKey ?? '')
    .split('-')
    .map(Number)
  if (!year || !month || !day) return 0
  return Math.floor(Date.UTC(year, month - 1, day) / 86400000)
}

/**
 * La frase de un día concreto.
 *
 * Determinista: la misma fecha devuelve siempre la misma frase, en el
 * dispositivo y sin red (§5.2, "Persistencia"). No hay azar ni estado guardado
 * que pueda desincronizarse.
 *
 * @param {string} dateKey - 'YYYY-MM-DD'
 * @param {object} [opciones]
 * @param {boolean} [opciones.animoBajoReciente] - Retira los temas de
 *        rendimiento (§5.3, Bloque 1). Por defecto, false.
 * @returns {{id: string, texto: string, tema: string, tipo: string, autor: string, fuente: string, atribucion: string}}
 */
export function fraseDelDia(dateKey, { animoBajoReciente = false } = {}) {
  const repertorio = animoBajoReciente
    ? FRASES.filter((frase) => !TEMAS_DE_RENDIMIENTO.includes(frase.tema))
    : FRASES

  const indice =
    ((diasDesdeEpoca(dateKey) % repertorio.length) + repertorio.length) % repertorio.length
  return repertorio[indice]
}

/**
 * Las cadenas de una frase que tienen que pasar el léxico de §3.6.
 *
 * **Una cita no se revisa por su texto, y no es una relajación de la regla: es
 * lo que una cita es.** Es texto histórico en dominio público, reproducido de
 * una edición de referencia; corregirlo para que pase el léxico lo dejaría de
 * ser. Nervo escribió «¡Vida, estamos en paz!» con esa exclamación, y Strivo
 * no la firma: la atribuye. Lo que sí se revisa siempre es la `atribucion`
 * —esa la escribimos nosotros— y el `texto` de las originales, que es voz de
 * Strivo aunque se inspire en otro.
 *
 * Vive aquí, junto a los datos, y no dentro del script de léxico ni dentro de
 * la prueba: los dos la consumen, y dos copias de la misma regla envejecen
 * distinto (§11, "Dónde vive cada regla").
 *
 * @param {{texto?: string, tipo?: string, atribucion?: string}} frase
 * @returns {string[]} Las cadenas revisables, sin huecos.
 */
export function revisablesDe(frase) {
  if (!frase) return []
  const texto = frase.tipo === 'cita' ? '' : frase.texto
  return [texto, frase.atribucion].filter((cadena) => typeof cadena === 'string' && cadena !== '')
}

