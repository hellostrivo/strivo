// src/content/frases-del-dia.js
// Repertorio de frases del día (§5.3, Bloque 1 · RN-HOY-02).
//
// Va en `content/` y no dentro del componente ni dentro de la spec: es material
// editorial, crece con el tiempo y se revisa aparte del código que lo pinta.
//
// **Tamaño del repertorio.** RN-HOY-02 pide que una frase no se repita en 365
// días. Este repertorio tiene 200 entradas, así que la no repetición está
// garantizada durante 200 días. `diasSinRepetir` lo dice en voz alta para que
// nadie tenga que contarlas a mano.
//
// **Dos tipos de entrada** (`tipo`):
//   · 'original' — redacción propia de Strivo inspirada en una obra antigua.
//     Se muestra SIN comillas. Atribución: "Versión Strivo inspirada en X".
//   · 'cita' — reproducción textual de una obra en dominio público (autor
//     fallecido hace más de cien años y obra publicada antes de 1931). Se
//     muestra ENTRE COMILLAS. Atribución: "Autor · Obra".
//
// **Reglas editoriales que no se pueden romper** (ver el documento fuente
// `docs/200-frases-fuentes.md`):
//   · No convertir una 'original' en cita: nunca "dijo" ni "escribió".
//   · No mostrar solo el nombre del autor tras un guion en una 'original'.
//   · No corregir ni modernizar el texto de una 'cita' sin cotejarlo con la
//     edición de referencia. La puntuación y las mayúsculas son de la edición.
//   · No convertir una cita en eslogan, nombre de función o campaña sin
//     revisar antes posibles marcas.
//
// **Saltos de verso.** Las citas en verso llevan `\n`. El componente que las
// pinta necesita `white-space: pre-line` para respetarlos.
//
// **Ninguna frase lleva marca de género en el trato a la persona usuaria.**
// Están redactadas para que no haga falta el helper de §3.6.5: una frase
// distinta cada día en tres versiones sería mantener tres repertorios.
//
// **Orden.** Las entradas van intercaladas a propósito: el tema rota en el
// ciclo gratitud → calma → identidad → aceptación → esfuerzo, y el tipo
// alterna cada vuelta. Como `fraseDelDia()` recorre el array por índice de
// día, agruparlas por tema daría cuarenta días consecutivos del mismo tema.
// Al añadir entradas nuevas, respetar el ciclo o reordenar el array entero.
//
// Temas (§5.3): gratitud · calma · esfuerzo · identidad · aceptacion.

